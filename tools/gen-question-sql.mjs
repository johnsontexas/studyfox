// Writes supabase/question_expansion.sql from the seed files:
//   supabase/seed/ap-gap-bank.mjs   -> public.ap_questions (regular bank, new units)
//   js/content/challenge-bank.js    -> public.questions / public.ap_questions with challenge = true
// Run: node tools/gen-question-sql.mjs   (re-running the SQL is safe: rows are skipped if the stem exists)
import { writeFileSync } from 'node:fs';
import { GAP } from '../supabase/seed/ap-gap-bank.mjs';
import { CHALLENGE_SRC } from '../js/content/challenge-bank.js';

const s = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v == null ? 'null' : `${s(JSON.stringify(v))}::jsonb`);
const check = (q) => {
  if (q.choices.length !== 4 || q.why.length !== 4 || !(q.answer >= 0 && q.answer < 4) || !q.expl || new Set(q.choices).size !== 4) throw new Error('Bad question: ' + q.stem);
};
const ap = (q, challenge) => `insert into public.ap_questions (course_id, unit, concept, difficulty, stem, choices, answer, expl, choice_expl, challenge)
select ${s(q.cid)}, ${s(q.unit)}, ${s(q.concept)}, ${q.difficulty || 3}, ${s(q.stem)}, ${j(q.choices)}, ${q.answer}, ${s(q.expl)}, ${j(q.why)}, ${challenge}
where not exists (select 1 from public.ap_questions where course_id = ${s(q.cid)} and stem = ${s(q.stem)});`;
const sat = (q) => {
  const passage = '', stem = q.stem; // the Hardest set shows one text block, so the passage stays in the stem
  return `insert into public.questions (test, section, domain, skill, difficulty, passage, stem, choices, answer, expl, choice_expl, challenge)
select 'SAT', ${s(q.sat)}, ${s(q.domain)}, ${s(q.skill)}, 3, ${s(passage)}, ${s(stem)}, ${j(q.choices)}, ${q.answer}, ${s(q.expl)}, ${j(q.why)}, true
where not exists (select 1 from public.questions where stem = ${s(stem)});`;
};
[...GAP, ...CHALLENGE_SRC].forEach(check);
const out = ['-- GENERATED by tools/gen-question-sql.mjs. Run supabase/challenge_questions.sql first.', 'begin;',
  `-- ${GAP.length} new regular AP questions`, ...GAP.map((q) => ap(q, false)),
  `-- ${CHALLENGE_SRC.length} Hardest questions`, ...CHALLENGE_SRC.map((q) => (q.sat ? sat(q) : ap(q, true))), 'commit;', ''];
writeFileSync(new URL('../supabase/question_expansion.sql', import.meta.url), out.join('\n'));
console.log(`Wrote ${GAP.length} gap + ${CHALLENGE_SRC.length} challenge questions.`);
