// Copies the website's color tokens (brand green, content colors) into the app, so the two never drift apart.
// Runs automatically before `npm start`, `npm run web`, and EAS builds. Safe to run any time.
// Content, generators, decks, store logic, and legal text are NOT copied: the app imports them
// straight from ../js, so editing the website updates the app too.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(resolve(here, '../../css/styles.css'), 'utf8');

function vars(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`Could not find ${selector} in css/styles.css`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  const out = {};
  for (const m of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) out[m[1].replace(/-(\w)/g, (_, c) => c.toUpperCase())] = m[2].trim();
  return out;
}

const light = vars(':root {');
const dark = { ...light, ...vars(':root[data-theme="dark"] {') };
for (const t of [light, dark]) for (const k of Object.keys(t)) if (!/^#|^rgba?\(/.test(t[k])) delete t[k];

const out = `// GENERATED by scripts/sync-web.mjs from ../css/styles.css. Do not edit; edit the website's CSS instead.
export const TOKENS = ${JSON.stringify({ light, dark }, null, 2)} as const;
`;
const file = resolve(here, '../src/generated/site.ts');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out);
console.log(`Synced ${Object.keys(light).length} website color tokens into the app.`);
