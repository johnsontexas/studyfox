-- ---------- Contributors (Contributors page, footer credit, About page team) ----------
create table if not exists public.contributors (
  id bigint generated always as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  section text not null default 'contributor' check (section in ('creator', 'contributor', 'support', 'donor', 'influencer')),
  role text not null default '' check (char_length(role) <= 80),
  blurb text not null default '' check (char_length(blurb) <= 600),
  url text not null default '' check (url = '' or url ~ '^https://'),
  image_url text not null default '' check (image_url = '' or image_url ~ '^(https://|assets/)'),
  sort int not null default 0,
  hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- Editable pages: an intro plus sections of HTML. The About page reads slug 'about'.
create table if not exists public.site_pages (
  slug text primary key check (slug ~ '^[a-z0-9-]{1,40}$'),
  title text not null default '',
  intro text not null default '',
  sections jsonb not null default '[]'::jsonb check (jsonb_typeof(sections) = 'array'),
  updated_at timestamptz not null default now()
);
do $$ declare t text; begin
  foreach t in array array['contributors', 'site_pages'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "anyone reads %1$s" on public.%1$I', t);
    execute format('create policy "anyone reads %1$s" on public.%1$I for select using (true)', t);
    execute format('drop policy if exists "admins write %1$s" on public.%1$I', t);
    execute format('create policy "admins write %1$s" on public.%1$I for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))', t);
    execute format('drop trigger if exists touch on public.%I', t);
    execute format('create trigger touch before update on public.%I for each row execute function public.touch_updated_at()', t);
  end loop;
end $$;

