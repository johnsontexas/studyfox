-- Content version also changes when contributors or pages change (they load with the rest of the content).
create or replace function public.content_version() returns text language sql stable security definer set search_path = '' as $$
  select coalesce(greatest((select max(updated_at) from public.courses), (select max(updated_at) from public.lessons), (select max(updated_at) from public.decks),
    (select max(updated_at) from public.questions), (select max(created_at) from public.hidden_questions), (select max(updated_at) from public.content_settings),
    (select max(updated_at) from public.contributors), (select max(updated_at) from public.site_pages))::text, '')
    || ':' || (select count(*) from public.hidden_questions)::text || ':' || (select count(*) from public.lessons)::text || ':' || (select count(*) from public.courses)::text
    || ':' || (select count(*) from public.questions)::text || ':' || (select count(*) from public.decks)::text || ':' || (select count(*) from public.content_settings)::text
    || ':' || (select count(*) from public.contributors)::text || ':' || (select count(*) from public.site_pages)::text;
$$;
grant execute on function public.content_version() to anon, authenticated;

-- ---------- User numbers ----------
-- Every account gets the next number when it's created: the first student is #1. Numbers come from an
-- identity sequence, so they only go up and are never reused. Deleting an account keeps its row with
-- user_id set to null (and the name cleared), so the number stays retired and nobody else's number moves.
create table if not exists public.members (
  no bigint generated by default as identity primary key,
  user_id uuid unique references auth.users (id) on delete set null,
  display_name text not null default '' check (char_length(display_name) <= 40),
  show_on_leaderboard boolean not null default true,
  referred_by bigint references public.members (no) on delete set null,
  referred_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists members_referred_by on public.members (referred_by);
alter table public.members enable row level security;
drop policy if exists "students read their own number" on public.members;
create policy "students read their own number" on public.members for select to authenticated using (user_id = (select auth.uid()) or (select public.is_admin()));
-- No insert/update/delete policies: rows are created by the trigger below and changed only through the functions.

-- A deleted account keeps its number, but nothing that identifies the person.
create or replace function public.scrub_deleted_member() returns trigger language plpgsql set search_path = '' as $$
begin
  if new.user_id is null and old.user_id is not null then new.display_name := ''; new.show_on_leaderboard := false; end if;
  return new;
end $$;
drop trigger if exists scrub_deleted_member on public.members;
create trigger scrub_deleted_member before update on public.members for each row execute function public.scrub_deleted_member();

-- Number existing accounts in sign-up order (only once, before the trigger exists).
do $$ begin
  if not exists (select 1 from public.members) then
    insert into public.members (no, user_id, display_name, created_at) overriding system value
    select row_number() over (order by u.created_at, u.id), u.id,
      left(split_part(coalesce(nullif(u.raw_user_meta_data->>'full_name', ''), u.raw_user_meta_data->>'name', ''), ' ', 1), 40), u.created_at
    from auth.users u;
    perform setval(pg_get_serial_sequence('public.members', 'no'), greatest(coalesce((select max(no) from public.members), 0), 1), (select count(*) > 0 from public.members));
  end if;
end $$;

create or replace function public.assign_member_no() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.members (user_id, display_name)
  values (new.id, left(split_part(coalesce(nullif(new.raw_user_meta_data->>'full_name', ''), new.raw_user_meta_data->>'name', ''), ' ', 1), 40))
  on conflict (user_id) do nothing;
  return null;
end $$;
revoke all on function public.assign_member_no() from public, anon, authenticated;
drop trigger if exists assign_member_no on auth.users;
create trigger assign_member_no after insert on auth.users for each row execute function public.assign_member_no();

-- The caller's number, who referred them, and how many friends joined with their number.
create or replace function public.my_member() returns table (no bigint, referred_by bigint, referrals bigint, display_name text, show_on_leaderboard boolean, total bigint)
language sql stable security definer set search_path = '' as $$
  select m.no, m.referred_by, (select count(*) from public.members r where r.referred_by = m.no and r.user_id is not null),
    m.display_name, m.show_on_leaderboard, (select count(*) from public.members where user_id is not null)
  from public.members m where m.user_id = (select auth.uid());
$$;
revoke all on function public.my_member() from public, anon;
grant execute on function public.my_member() to authenticated;

-- Record the friend who shared StudyFox. Once per account; you can't refer yourself or name a deleted
-- account, and the friend must have joined before you.
create or replace function public.set_referrer(friend bigint) returns text language plpgsql security definer set search_path = '' as $$
declare me public.members;
begin
  select * into me from public.members where user_id = auth.uid();
  if me.no is null then return 'no_account'; end if;
  if me.referred_by is not null then return 'already'; end if;
  if friend = me.no then return 'self'; end if;
  if not exists (select 1 from public.members where no = friend and user_id is not null and no < me.no) then return 'not_found'; end if;
  update public.members set referred_by = friend, referred_at = now() where no = me.no;
  return 'ok';
end $$;
revoke all on function public.set_referrer(bigint) from public, anon;
grant execute on function public.set_referrer(bigint) to authenticated;

-- The first name shown on the Top sharers list, and whether to appear there at all.
create or replace function public.update_member_profile(p_name text, p_show boolean) returns void language plpgsql security definer set search_path = '' as $$
begin
  update public.members set display_name = left(split_part(trim(coalesce(p_name, '')), ' ', 1), 40), show_on_leaderboard = coalesce(p_show, show_on_leaderboard)
  where user_id = auth.uid();
end $$;
revoke all on function public.update_member_profile(text, boolean) from public, anon;
grant execute on function public.update_member_profile(text, boolean) to authenticated;

-- Top sharers: first name and number only, for students who haven't opted out, ranked by friends who joined.
create or replace function public.top_sharers(lim int default 20) returns table (no bigint, name text, referrals bigint)
language sql stable security definer set search_path = '' as $$
  select m.no, coalesce(nullif(m.display_name, ''), 'Student'), count(r.no)
  from public.members m join public.members r on r.referred_by = m.no and r.user_id is not null
  where m.user_id is not null and m.show_on_leaderboard
  group by m.no, m.display_name order by count(r.no) desc, m.no limit least(greatest(lim, 1), 5000);
$$;
grant execute on function public.top_sharers(int) to anon, authenticated;
